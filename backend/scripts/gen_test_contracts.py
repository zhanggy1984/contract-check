from pathlib import Path

import pymupdf

OUT = Path(__file__).resolve().parents[1] / "data" / "test"
OUT.mkdir(parents=True, exist_ok=True)


def make_pdf(name: str, text: str) -> None:
    doc = pymupdf.open()
    page = doc.new_page()
    y = 50
    for line in text.split("\n"):
        if y > page.rect.height - 50:
            page = doc.new_page()
            y = 50
        page.insert_text((50, y), line, fontname="china-ss", fontsize=11)
        y += 20
    doc.save(OUT / f"{name}.pdf")
    doc.close()
    print("generated:", name)


